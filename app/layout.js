import "./globals.css";

import ProgressSender from "./progress-sender.js";
import { loadSite } from "../lib/site.js";
import { socialImage, socialTwitter } from "../lib/social.js";
import { renderSiteMenu } from "../legacy/src/site/shell.mjs";

const { config, icons } = loadSite();

/** The drawer the Menu button in the header opens. Rendered once here rather than by each route,
 *  because this host serves every page the menu links to: no row is gated and none needs an origin. */
const SITE_MENU = renderSiteMenu({ config, icons, projectsAvailable: true, appPagesAvailable: true });

const DESCRIPTION = "Zero-signup, in-browser Excel practice exercises with deterministic grading.";

export const metadata = {
  metadataBase: new URL(config.baseUrl),
  title: { default: config.name, template: `%s · ${config.name}` },
  description: DESCRIPTION,
  other: { "color-scheme": "light dark" },
  // The SVG favicon is what the page carries; the PNGs are what a phone's home screen and a maskable
  // slot take, and they are generated by the static build alongside the share cards.
  icons: {
    icon: [
      { url: "/assets/favicon.svg", type: "image/svg+xml" },
      { url: "/assets/icons/icon-192.png", sizes: "192x192", type: "image/png" },
    ],
    apple: [{ url: "/assets/icons/apple-touch-icon.png", sizes: "180x180", type: "image/png" }],
  },
  manifest: "/manifest.webmanifest",
  // The default for every page that does not override `openGraph`. A page that does override it has to
  // ask for its image itself — Next replaces the object rather than merging into it — which is what
  // `scripts/check-next-pages.mjs` enforces.
  openGraph: {
    type: "website",
    siteName: config.name,
    title: config.name,
    description: DESCRIPTION,
    url: "/",
    images: [socialImage({ path: "/", title: config.name })],
  },
  twitter: socialTwitter({ path: "/", title: config.name }),
};

/** `themeColor` moved out of `metadata` in Next 14; the light/dark pair is the same one the static
 *  head writes from `config.themeColor`, so the mobile browser bar matches the page in both themes. */
export const viewport = {
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: config.themeColor.light },
    { media: "(prefers-color-scheme: dark)", color: config.themeColor.dark },
  ],
};

export default function RootLayout({ children }) {
  return (
    <html lang={config.inLanguage}>
      <head>
        <link rel="preload" href="/assets/fonts/plex-sans-latin.woff2" as="font" type="font/woff2" crossOrigin="anonymous" />
        <link rel="preload" href="/assets/fonts/newsreader-latin.woff2" as="font" type="font/woff2" crossOrigin="anonymous" />
      </head>
      {/* `body.lesson` / `body.track` exist in the legacy markup but no rule selects on them. */}
      <body className="light">
        {children}
        {/* `showModal` takes the drawer out of flow, so it can sit at the end of the document; the
            static build writes the same markup straight after the header. */}
        <div dangerouslySetInnerHTML={{ __html: SITE_MENU }} />
        <script type="module" src="/assets/client/menu.js" />
        {/* The footer's feedback dialog is React-inserted markup, so its script cannot ride along in
            the fragment: a script set through innerHTML never runs. */}
        <script type="module" src="/assets/client/feedback.js" />
        {/* The exercise's event buffer is the browser's record of what happened; this posts it. Inert on
            a deployment without accounts (the API refuses, and the sender stops there). */}
        <ProgressSender />
      </body>
    </html>
  );
}
