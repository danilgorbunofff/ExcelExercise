/**
 * Vale, fed from the same rules as `npm run content:copy`.
 *
 * The phrase list and the structural patterns live once, in `packages/content-lint/data/copy-rules.json`.
 * Vale does not read that file, so this script writes the Vale style from it and exports the prose that
 * lives in JSON (lessons) and in the rendered pages (the site-copy inventory) as Markdown Vale can read.
 * Two engines, one rule file: a phrase added there reaches both on the next run.
 *
 *   node scripts/vale-sync.mjs           # write .vale/styles/ExcelSupreme and .vale/export
 *   node scripts/vale-sync.mjs --check   # fail if the committed style is out of date (the test uses this)
 *
 * The style is committed; the export is not (it is a view of content that is already committed).
 * Everything Vale reports here is a warning: a pattern is a reason to reread a sentence, not a verdict.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join } from "node:path";

import { loadContent } from "../packages/content/index.js";
import { lessonFields, loadRules } from "../packages/content-lint/copy.js";

const ROOT = join(import.meta.dirname, "..");
const STYLE_DIR = join(ROOT, ".vale", "styles", "ExcelSupreme");
const EXPORT_DIR = join(ROOT, ".vale", "export");
const RULES = "packages/content-lint/data/copy-rules.json";

const checkOnly = process.argv.includes("--check");

const HEADER = `# Generated by scripts/vale-sync.mjs from ${RULES}. Edit the rules there, then run \`npm run vale:sync\`.\n`;

const escapeRegex = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const yamlString = (text) => JSON.stringify(text);

function styleFiles(rules) {
  const files = new Map();

  files.set(
    "BannedPhrases.yml",
    `${HEADER}extends: existence
message: "'%s' is a phrase generated marketing copy leans on. Say the plain thing (reasons: ${RULES})."
level: warning
ignorecase: true
tokens:
${rules.bannedPhrases.map((entry) => `  - ${yamlString(escapeRegex(entry.phrase))}`).join("\n")}
`,
  );

  for (const entry of rules.patterns ?? []) {
    const name = entry.id
      .split("-")
      .map((part) => part[0].toUpperCase() + part.slice(1))
      .join("");
    files.set(
      `Pattern${name}.yml`,
      `${HEADER}extends: existence
message: ${yamlString(`'%s': ${entry.why}`)}
level: warning
ignorecase: true
raw:
  - ${yamlString(entry.regex)}
`,
    );
  }

  files.set(
    "Typography.yml",
    `${HEADER}extends: existence
message: "'%s' is a typographic mark the house style leaves out (use a comma, a full stop, straight quotes or three dots)."
level: warning
nonword: true
tokens:
  - "\\u2014"
  - "\\u2013"
  - "[\\u201c\\u201d]"
  - "[\\u2018\\u2019]"
  - "\\u2026"
`,
  );

  files.set(
    "SentenceLength.yml",
    `${HEADER}extends: occurrence
message: "This sentence runs past ${rules.sentence.maxWords} words. ${rules.sentence.why}."
level: warning
scope: sentence
max: ${rules.sentence.maxWords}
token: '\\b(\\w+)\\b'
`,
  );

  files.set(
    "Openers.yml",
    `${HEADER}extends: existence
message: "Starting with '%s' is filler. Start with the thing."
level: warning
nonword: true
scope: sentence
raw:
  - ${yamlString(`^(?:${rules.bannedOpeners.map((entry) => escapeRegex(entry.phrase.trim().replace(/,$/, ""))).join("|")}),`)}
`,
  );

  return files;
}

/** One lesson's prose as Markdown: a heading per field, a paragraph per paragraph. */
function lessonMarkdown(lesson) {
  const parts = [`# ${lesson.id}\n`];
  for (const field of lessonFields(lesson)) {
    if (!field.prose) continue;
    parts.push(`## ${field.field}\n\n${String(field.text).trim()}\n`);
  }
  return parts.join("\n");
}

/** The Markdown pages, minus a front matter block that is not always valid YAML (Vale refuses to parse it). */
function exportPages(from, to) {
  const dir = join(ROOT, "legacy", "content", from);
  if (!existsSync(dir)) return 0;
  mkdirSync(join(EXPORT_DIR, to), { recursive: true });
  let count = 0;
  for (const name of readdirSync(dir).filter((file) => file.endsWith(".md"))) {
    // Table rows are data (a "—" in a shortcut table means "no equivalent"), and the copy gate skips them too.
    const body = readFileSync(join(dir, name), "utf8")
      .replace(/^---\n[\s\S]*?\n---\n/, "")
      .split("\n")
      .filter((line) => !line.trimStart().startsWith("|"))
      .join("\n");
    writeFileSync(join(EXPORT_DIR, to, name), body);
    count += 1;
  }
  return count;
}

function siteMarkdown() {
  const inventory = JSON.parse(readFileSync(join(ROOT, "tests", "golden", "site-copy.json"), "utf8"));
  const seen = new Set();
  const lines = ["# Site copy\n"];
  for (const [key, text] of inventory) {
    // A string repeated on 139 pages is one sentence to review, not 139.
    if (seen.has(text) || text.trim().length < 20) continue;
    seen.add(text);
    lines.push(`<!-- ${key} -->\n${text.trim()}\n`);
  }
  return lines.join("\n");
}

function main() {
  const rules = loadRules();
  const files = styleFiles(rules);

  if (checkOnly) {
    const stale = [];
    for (const [name, body] of files) {
      const path = join(STYLE_DIR, name);
      if (!existsSync(path) || readFileSync(path, "utf8") !== body) stale.push(name);
    }
    const extra = existsSync(STYLE_DIR) ? readdirSync(STYLE_DIR).filter((name) => !files.has(name)) : [];
    if (stale.length || extra.length) {
      console.error(`vale style is out of date (${[...stale, ...extra.map((n) => `${n} (orphan)`)].join(", ")}); run npm run vale:sync`);
      process.exit(1);
    }
    console.log(`vale style: ${files.size} rule files match ${RULES}`);
    return;
  }

  rmSync(STYLE_DIR, { recursive: true, force: true });
  mkdirSync(STYLE_DIR, { recursive: true });
  for (const [name, body] of files) writeFileSync(join(STYLE_DIR, name), body);

  rmSync(EXPORT_DIR, { recursive: true, force: true });
  mkdirSync(join(EXPORT_DIR, "lessons"), { recursive: true });
  const content = loadContent(join(ROOT, "legacy", "content"));
  for (const lesson of content.exercises) {
    writeFileSync(join(EXPORT_DIR, "lessons", `${lesson.id}.md`), lessonMarkdown(lesson));
  }
  const pages = ["articles", "formulas", "shortcuts"].reduce((total, dir) => total + exportPages(dir, dir), 0);
  writeFileSync(join(EXPORT_DIR, "site.md"), siteMarkdown());

  console.log(`vale: wrote ${files.size} rule files, ${content.exercises.length} lessons and ${pages} pages to .vale/`);
}

main();
